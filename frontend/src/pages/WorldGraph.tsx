function Between({ center, nodes }: { center: Entity; nodes: GNode[] }) {
  const [other, setOther] = useState<Entity | null>(null);
  const [loose, setLoose] = useState(false);
  const [otherFor, setOtherFor] = useState(center.id);
  if (otherFor !== center.id) { setOtherFor(center.id); setOther(null); }
  const companies = nodes.filter((n) => n.id !== center.id && ["company", "organization"].includes(n.kind));
  const q = { a: center.id, b: other?.id ?? 0, unreferenced: loose };
  const shared = useQuery({ queryKey: ["wg-shared", q], queryFn: () => api.get<{ shared: { entity: Entity; via_a: Edge[]; via_b: Edge[] }[]; note: string | null }>("/world-graph/shared", q), enabled: !!other });
  const path = useQuery({ queryKey: ["wg-path", q], queryFn: () => api.get<{ found: boolean; steps: { from: Entity; to: Entity; edge: Edge }[]; max_hops: number; note: string | null }>("/world-graph/path", q), enabled: !!other });
  return (
    <section className="card wg-between">
      <h2 className="wg-h2">Connections between {center.name} and {other && other.id !== center.id && other.name ? other.name : "…"}</h2>
      <div className="wg-between-pick">
        {companies.length > 0 && (
          <label className="fld"><span>An entity in this graph</span>
            <select className="input" value={other && companies.some((c) => c.id === other.id) ? other.id : ""} onChange={(e) => setOther(companies.find((c) => c.id === Number(e.target.value)) ?? null)}>
              <option value="">Choose…</option>
              {companies.map((c) => <option key={c.id} value={c.id}>{c.name}</option>)}
            </select>
          </label>
        )}
        <div className="fld"><span>Or another company</span><EntitySearch label="Find a company to compare" onPick={setOther} /></div>
      </div>
      <label className="wg-check"><input type="checkbox" checked={loose} onChange={(e) => setLoose(e.target.checked)} /> Include unreferenced statements</label>
      {other && other.id === center.id && <p className="np-note">Pick a different company.</p>}
      {other && other.id !== center.id && (
        <div className="wg-between-out">
          {(shared.isLoading || path.isLoading) && <Loading />}
          {(shared.error || path.error) && <ErrorState error={shared.error || path.error} />}
          {path.data && (
            <div>
              <h3>Shortest chain</h3>
              {path.data.found ? (
                <ol className="wg-path">{path.data.steps.map((s, i) => <li key={i}>{s.from.name} → <b>{s.to.name}</b> <span className="muted small">({s.edge.label})</span> <StatusBadge s={s.edge.status} /></li>)}</ol>
              ) : <p className="small muted">No chain of up to {path.data.max_hops} {loose ? "" : "referenced "}links between them in the relationships loaded so far.{loose ? "" : " Including unreferenced statements may find one."}</p>}
              {path.data.note && <p className="np-note">{path.data.note}</p>}
            </div>
          )}
          {shared.data && (
            <div>
              <h3>Shared direct connections</h3>
              {shared.data.shared.length ? (
                <ul className="wg-rels">{shared.data.shared.map((s) => <li key={s.entity.id}><b>{s.entity.name}</b> <span className="muted small">— {s.via_a[0]?.label} ({STATUS_LABEL[s.via_a[0]?.status]}) / {s.via_b[0]?.label} ({STATUS_LABEL[s.via_b[0]?.status]})</span></li>)}</ul>
              ) : <p className="small muted">None {loose ? "" : "among referenced links "}in the relationships loaded so far.</p>}
            </div>
          )}
        </div>
      )}
    </section>
  );
}
