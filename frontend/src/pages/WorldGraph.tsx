function Inspector({ data, nodes, sel, onExpand, shown, onCentre, onSelect, pending }: {
  data: Graph; nodes: Map<number, GNode>; sel: { node?: number; edge?: number }; onExpand: (id: number) => void; shown: number[]; onCentre: (id: number) => void;
  onSelect: (s: { node?: number; edge?: number }) => void; pending: boolean;
}) {
  const edge = sel.edge ? data.edges.find((e) => e.id === sel.edge) : undefined;
  const node = sel.node ? nodes.get(sel.node) : undefined;
  return (
    <aside className="card wg-inspector" aria-live="polite" aria-label="Details">
      {edge ? (
        <>
          <h3>{sentence(edge, nodes)}</h3>
          <p className="small"><StatusBadge s={edge.status} /> {STATUS.find((s) => s.key === edge.status)?.help}</p>
          <p className="muted small">{edge.valid_from ? `From ${edge.valid_from}. ` : ""}{edge.valid_to ? `Until ${edge.valid_to}. ` : ""}{!edge.valid_from && !edge.valid_to ? "The source gives no dates. " : ""}Last checked {day(edge.last_verified)}.</p>
          <h4>Evidence ({edge.evidence.length})</h4>
          <EvidenceList items={edge.evidence} />
        </>
      ) : node ? (
        <>
          <h3>{displayName(node.name)}</h3>
          <p className="muted small">{KIND_LABEL[node.kind] ?? node.kind}{node.description ? ` · ${node.description}` : ""}</p>
          <div className="row">
            {node.id !== data.center.id && <button type="button" className="btn primary sm" onClick={() => onCentre(node.id)}>Centre on this</button>}
            {node.expandable && !shown.includes(node.id) && node.id !== data.center.id && <button type="button" className="btn sm" disabled={pending} onClick={() => onExpand(node.id)}>{pending ? "Loading…" : "Show its connections"}</button>}
            {node.symbol && <Link className="btn sm" to={`/markets/${encodeURIComponent(node.symbol)}`}>Market page</Link>}
            {node.wikidata_url && <a className="btn sm" href={node.wikidata_url} target="_blank" rel="noopener noreferrer nofollow">Wikidata ↗<span className="sr-only"> (opens in a new tab)</span></a>}
          </div>
          <h4>Relationships shown</h4>
          <ul className="wg-rels">
            {data.edges.filter((e) => e.source_id === node.id || e.target_id === node.id).map((e) => (
              <li key={e.id}><button type="button" className="linkish" onClick={() => onSelect({ edge: e.id })}>{sentence(e, nodes)}</button> <StatusBadge s={e.status} /></li>
            ))}
          </ul>
        </>
      ) : (
        <>
          <h3>Inspect a link or entity</h3>
          <p className="muted small">Select any entity or line to see what it is, where the information comes from, and how sure we can be.</p>
          <p className="small">{data.nodes.length - 1} connected entities · {data.edges.length} relationships · {data.counts.verified} referenced, {data.counts.uncertain} unreferenced{data.counts.historical ? `, ${data.counts.historical} ended` : ""}.</p>
        </>
      )}
    </aside>
  );
}

// ---------------------------------------------------------------------------------------------- saving

function SaveInvestigation({ graph, savedId, state, onSaved }: { graph: Graph; savedId: number | null; state: SavedState; onSaved: (id: number) => void }) {
  const qc = useQueryClient();
  const [open, setOpen] = useState(false);
  const [title, setTitle] = useState("");
  const [done, setDone] = useState<string | null>(null);
  const save = useMutation({
    mutationFn: () => savedId
      ? api.patch<Saved>(`/saved-research/${savedId}`, { state })
      : api.post<Saved>("/saved-research", { kind: "graph", title: title.trim() || `${graph.center.name} — ${new Date().toISOString().slice(0, 10)}`, entity_id: graph.center.id, state }),
    onSuccess: (it) => { setOpen(false); setDone(savedId ? "Updated" : "Saved"); qc.invalidateQueries({ queryKey: ["saved-research"] }); qc.invalidateQueries({ queryKey: ["wg-graph"] }); onSaved(it.id); },
  });
  if (savedId) {
    return (
      <span className="row">
        <button type="button" className="btn" disabled={save.isPending} onClick={() => save.mutate()}>{save.isPending ? "Saving…" : "Update saved investigation"}</button>
        {done && <span className="small muted" role="status">{done}</span>}
        {save.error && <span className="small neg" role="alert">{errorMessage(save.error)}</span>}
      </span>
    );
  }
  if (!open) return <button type="button" className="btn" onClick={() => { setTitle(`${graph.center.name} connections`); setOpen(true); }}>Save investigation</button>;
  return (
    <form className="row wg-save" onSubmit={(e) => { e.preventDefault(); save.mutate(); }}>
      <label className="sr-only" htmlFor="wg-save-title">Name</label>
      <input id="wg-save-title" className="input" value={title} maxLength={200} onChange={(e) => setTitle(e.target.value)} />
      <button className="btn primary" disabled={save.isPending}>{save.isPending ? "Saving…" : "Save"}</button>
      <button type="button" className="btn ghost" onClick={() => setOpen(false)}>Cancel</button>
      {save.error && <span className="small neg" role="alert">{errorMessage(save.error)}</span>}
    </form>
  );
}

