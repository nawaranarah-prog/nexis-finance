function EntityView({ id }: { id: number }) {
  const [sp, setSp] = useSearchParams();
  const nav = useNavigate();
  const depth = sp.get("depth") === "2" ? 2 : 1;
  // Filters live in the URL (shareable, saved with an investigation) but update on screen at once: the URL change
  // lands a moment later, and a checkbox must never flick back in between.
  const urlFilters = { status: sp.get("status") ?? "", types: sp.get("types") ?? "" };
  const [filters, setFilters] = useState(urlFilters);
  const [filtersFrom, setFiltersFrom] = useState(urlFilters);
  if (filtersFrom.status !== urlFilters.status || filtersFrom.types !== urlFilters.types) { setFiltersFrom(urlFilters); setFilters(urlFilters); }
  const status = csv(filters.status) as Status[];
  const types = csv(filters.types);
  const expanded = csv(sp.get("expanded")).map(Number).filter(Boolean);
  const savedId = Number(sp.get("saved")) || null;
  const [phone] = useState(() => typeof window !== "undefined" && !!window.matchMedia?.("(max-width: 640px)").matches);
  const [view, setView] = useState<"graph" | "list">(phone ? "list" : "graph");
  const [sel, setSel] = useState<{ node?: number; edge?: number }>({});
  const [selFor, setSelFor] = useState(id);
  if (selFor !== id) { setSelFor(id); setSel({}); }  // a new centre starts with nothing selected

  const params = { depth, status: status.join(",") || undefined, types: types.join(",") || undefined, expanded: expanded.join(",") || undefined, saved: savedId ?? undefined };
  const g = useQuery({
    queryKey: ["wg-graph", id, params],
    queryFn: () => api.get<Graph>(`/world-graph/entities/${id}/graph`, params),
    placeholderData: (prev) => (prev && prev.center.id === id ? prev : undefined),
  });
  const set = (k: string, v: string | null) => {
    const n = new URLSearchParams(sp);
    if (v) n.set(k, v); else n.delete(k);
    setSp(n, { replace: true });
  };
  const toggle = (k: "status" | "types", all: string[], key: string) => {
    const cur = csv(filters[k]);
    const base = cur.length ? cur : all;
    const next = base.includes(key) ? base.filter((x) => x !== key) : [...base, key];
    const v = next.length === all.length || next.length === 0 ? null : next.join(",");
    setFilters({ ...filters, [k]: v ?? "" });
    set(k, v);
  };
  const expand = (nid: number) => set("expanded", [...new Set([...expanded, nid])].slice(-10).join(","));

  if (g.isLoading) return <Loading label="Loading relationships (first view fetches them from Wikidata)" />;
  if (g.error) return <><EntitySearch label="Search for a company" onPick={(e) => nav(`/world-graph/${e.id}`)} /><ErrorState error={g.error} onRetry={() => g.refetch()} /></>;
  const data = g.data!;
  const nodes = new Map(data.nodes.map((n) => [n.id, n]));
  const activeStatus = status.length ? status : STATUS.map((s) => s.key);
  const activeTypes = types.length ? types : TYPES.map((t) => t.key);

  return (
    <>
      <div className="wg-top">
        <EntitySearch label="Search another company" onPick={(e) => nav(`/world-graph/${e.id}`)} />
      </div>
      {data.since_saved?.changed && (
        <div className="banner warn small" role="status">
          The data changed since you saved this investigation: {data.since_saved.added} new, {data.since_saved.removed} removed, {data.since_saved.status_changed} with a different evidence status.
        </div>
      )}
      {data.fetch?.stale && <p className="np-note" role="status">Wikidata couldn't be reached, so these are the relationships saved on {day(data.fetch.fetched_at)}.</p>}

      <div className="wg-center-head">
        <div>
          <h2>{data.center.name}</h2>
          <p className="muted small">
            {KIND_LABEL[data.center.kind] ?? data.center.kind}{data.center.description && data.center.description.toLowerCase() !== data.center.kind ? ` · ${data.center.description}` : ""}
            {data.center.relations_fetched_at ? ` · relationships checked ${day(data.center.relations_fetched_at)}` : ""}
          </p>
        </div>
        <div className="row">
          {data.center.symbol && <Link className="btn" to={`/markets/${encodeURIComponent(data.center.symbol)}`}>Market page</Link>}
          {data.center.symbol && <ResearchLinks symbol={data.center.symbol} except="graph" size="" />}
          <SaveInvestigation graph={data} savedId={savedId} state={{ depth, status, types, expanded, signature: data.signature }} onSaved={(sid) => set("saved", String(sid))} />
        </div>
      </div>

      <div className="wg-toolbar" aria-label="Graph options">
        <div className="wg-tool"><span className="wg-tool-label" id="wg-depth">Depth</span>
          <Seg value={depth} options={[{ value: 1, label: "Direct links" }, { value: 2, label: "Two steps" }]} onChange={(v) => set("depth", v === 2 ? "2" : null)} /></div>
        <div className="wg-tool"><span className="wg-tool-label">View</span>
          <Seg value={view} options={[{ value: "graph", label: "Graph" }, { value: "list", label: "List" }]} onChange={setView} /></div>
        <details className="wg-filters" open={!phone}>
        <summary>Filters</summary>
        <div className="wg-filters-body">
        <fieldset className="wg-filter"><legend>Evidence</legend>
          {STATUS.map((s) => (
            <label key={s.key} className={`wg-check st-${s.key}`} title={s.help}>
              <input type="checkbox" checked={activeStatus.includes(s.key)} onChange={() => toggle("status", STATUS.map((x) => x.key), s.key)} />
              <span className="wg-swatch" aria-hidden /> {s.label} <span className="muted">({data.counts[s.key] ?? 0})</span>
            </label>
          ))}
        </fieldset>
        <fieldset className="wg-filter"><legend>Relationships</legend>
          {TYPES.map((t) => (
            <label key={t.key} className="wg-check">
              <input type="checkbox" checked={activeTypes.includes(t.key)} onChange={() => toggle("types", TYPES.map((x) => x.key), t.key)} /> {t.label}
            </label>
          ))}
        </fieldset>
        </div>
        </details>
      </div>
      {data.truncated > 0 && <p className="np-note" role="status">Showing {data.nodes.length} of {data.nodes.length + data.truncated} connected entities (the graph is capped at {data.max_nodes}). Use the filters to narrow it — better-sourced links are kept first.</p>}

      <div className="wg-main">
        <div className="wg-canvas">
          {data.edges.length === 0 ? (
            <p className="state">No relationships match these filters{data.counts.verified + data.counts.uncertain + data.counts.historical === 0 ? " — Wikidata has none of these relationship types for this entity" : ""}.</p>
          ) : view === "graph" ? (
            <GraphSvg data={data} sel={sel} onSelect={setSel} shown={expanded} />
          ) : phone ? (
            <EdgeCards data={data} nodes={nodes} onSelect={setSel} />
          ) : (
            <EdgeTable data={data} nodes={nodes} onSelect={setSel} />
          )}
          <Legend />
        </div>
        <Inspector data={data} nodes={nodes} sel={sel} onExpand={expand} shown={expanded} onCentre={(nid) => nav(`/world-graph/${nid}`)} onSelect={setSel} pending={g.isFetching} />
      </div>

      <Between center={data.center} nodes={data.nodes} />
      <p className="muted xs wg-foot">Source: Wikidata (CC0), community-edited, cached for up to 7 days. “Referenced” means the statement cites a source — open it to check. Nexis adds no relationships of its own here.</p>
    </>
  );
}

// ---------------------------------------------------------------------------------------------- the drawing

interface Pos { x: number; y: number; a: number; sector: number }

/** Deterministic radial layout: the centre in the middle, direct links on the first ring (grouped by relationship
    type), each further level fanned out beside the node it hangs from. Same data → same picture. */
export function layout(data: Pick<Graph, "center" | "nodes" | "edges">): Map<number, Pos> {
  const pos = new Map<number, Pos>();
  const first = data.nodes.filter((n) => n.level === 1).length;
  const R = [0, Math.max(210, first * 15), 0, 0, 0];
  R[2] = R[1] + 150; R[3] = R[2] + 110; R[4] = R[3] + 90;
  pos.set(data.center.id, { x: 0, y: 0, a: 0, sector: Math.PI * 2 });
  const order: Record<string, number> = { subsidiary_of: 0, owned_by: 1, listed_on: 2, in_industry: 3, located_in: 4 };
  const typeOf = (nid: number, parent: number) => data.edges.find((e) => (e.source_id === nid && e.target_id === parent) || (e.target_id === nid && e.source_id === parent))?.type ?? "";
  const maxLevel = Math.max(0, ...data.nodes.map((n) => n.level));
  for (let L = 1; L <= maxLevel; L++) {
    const here = data.nodes.filter((n) => n.level === L);
    const groups = new Map<number, typeof here>();
    for (const n of here) {
      const parent = data.edges.map((e) => (e.source_id === n.id ? e.target_id : e.target_id === n.id ? e.source_id : null))
        .find((p) => p !== null && pos.has(p) && (data.nodes.find((m) => m.id === p)?.level ?? (p === data.center.id ? 0 : 99)) === L - 1) ?? data.center.id;
      groups.set(parent, [...(groups.get(parent) ?? []), n]);
    }
    for (const [parent, kids] of groups) {
      const pp = pos.get(parent)!;
      kids.sort((a, b) => (order[typeOf(a.id, parent)] ?? 9) - (order[typeOf(b.id, parent)] ?? 9) || a.name.localeCompare(b.name));
      const span = L === 1 ? Math.PI * 2 : Math.min(pp.sector * 0.92, Math.PI * 0.9);
      const step = span / Math.max(kids.length, 1);
      const r = R[Math.min(L, R.length - 1)];
      kids.forEach((k, j) => {
        // a half-step offset keeps the first ring symmetric and nodes off the exact top and bottom
        const a = L === 1 ? -Math.PI / 2 + (j + 0.5) * step : pp.a + (j - (kids.length - 1) / 2) * step;
        pos.set(k.id, { x: Math.cos(a) * r, y: Math.sin(a) * r, a, sector: step });
      });
    }
  }
  return pos;
}

/** ``shown``: nodes whose own connections this view includes. (A node's relationships may already be stored because
    someone else opened it; that doesn't mean they're on screen here.) */
function GraphSvg({ data, sel, onSelect, shown }: { data: Graph; sel: { node?: number; edge?: number }; onSelect: (s: { node?: number; edge?: number }) => void; shown: number[] }) {
  const pos = useMemo(() => layout(data), [data]);
  // labels run outwards along each spoke, so the drawing's bounds are the outermost node plus room for a label
  const extent = Math.max(260, ...[...pos.values()].map((p) => Math.hypot(p.x, p.y))) + 200;
  const home = { x: -extent, y: -extent, w: extent * 2, h: extent * 2 };
  const [vb, setVb] = useState(home);
  const [vbFor, setVbFor] = useState(extent);
  if (vbFor !== extent) { setVbFor(extent); setVb(home); }
  const svg = useRef<SVGSVGElement>(null);
  const drag = useRef<{ x: number; y: number; vb: typeof vb } | null>(null);
  const [px, setPx] = useState(800);
  const zoomBy = (f: number) => setVb((v) => {
    const w = Math.min(Math.max(v.w * f, 300), extent * 4);
    const h = (w * v.h) / v.w;
    return { x: v.x + (v.w - w) / 2, y: v.y + (v.h - h) / 2, w, h };
  });
  useEffect(() => {
    const el = svg.current;
    if (!el) return;
    const ro = new ResizeObserver(() => setPx(el.clientWidth || 800));
    ro.observe(el);
    const wheel = (e: WheelEvent) => {
      if (!e.ctrlKey && !e.metaKey && Math.abs(e.deltaY) < 40) return;  // a plain scroll keeps scrolling the page
      e.preventDefault();
      zoomBy(e.deltaY > 0 ? 1.15 : 1 / 1.15);
    };
    el.addEventListener("wheel", wheel, { passive: false });
    return () => { ro.disconnect(); el.removeEventListener("wheel", wheel); };
  });
  const unit = vb.w / Math.max(px, 1);  // SVG units per screen pixel: keeps text and strokes a constant on-screen size
  const fs = 12.5 * unit;
  const nodeR = (n: GNode) => (n.id === data.center.id ? 15 : 9 + Math.min(n.degree, 6)) * unit;
  const selEdges = new Set(sel.node ? data.edges.filter((e) => e.source_id === sel.node || e.target_id === sel.node).map((e) => e.id) : sel.edge ? [sel.edge] : []);

  return (
    <div className="wg-svg-wrap">
      <div className="wg-zoom" role="group" aria-label="Zoom">
        <button type="button" className="btn sm" onClick={() => zoomBy(1 / 1.25)} aria-label="Zoom in">+</button>
        <button type="button" className="btn sm" onClick={() => zoomBy(1.25)} aria-label="Zoom out">−</button>
        <button type="button" className="btn sm" onClick={() => setVb(home)}>Reset</button>
      </div>
      <svg ref={svg} className="wg-svg" viewBox={`${vb.x} ${vb.y} ${vb.w} ${vb.h}`} role="group" aria-label={`Relationship graph of ${data.center.name}. Use Tab to move between entities and Enter to inspect one; the List view shows the same data as a table.`}
        onPointerDown={(e) => { if ((e.target as Element).closest(".wg-node, .wg-edge-hit")) return; drag.current = { x: e.clientX, y: e.clientY, vb }; (e.currentTarget as Element).setPointerCapture(e.pointerId); }}
        onPointerMove={(e) => { const d = drag.current; if (!d) return; setVb({ ...d.vb, x: d.vb.x - (e.clientX - d.x) * unit, y: d.vb.y - (e.clientY - d.y) * unit }); }}
        onPointerUp={() => { drag.current = null; }}>
        <defs>
          <marker id="wg-arrow" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" className="wg-arrowhead" /></marker>
        </defs>
        {data.edges.map((e) => {
          const a = pos.get(e.source_id), b = pos.get(e.target_id);
          if (!a || !b) return null;
          const sn = data.nodes.find((n) => n.id === e.target_id);
          const dx = b.x - a.x, dy = b.y - a.y, len = Math.hypot(dx, dy) || 1;
          const pad = (sn ? nodeR(sn) : 10 * unit) + 3 * unit;
          const x2 = b.x - (dx / len) * pad, y2 = b.y - (dy / len) * pad;
          const on = selEdges.has(e.id);
          return (
            <g key={e.id}>
              <line className={`wg-edge st-${e.status}${on ? " on" : ""}`} x1={a.x} y1={a.y} x2={x2} y2={y2} strokeWidth={(on ? 2.6 : 1.4) * unit} markerEnd="url(#wg-arrow)"
                strokeDasharray={e.status === "uncertain" ? `${6 * unit} ${4 * unit}` : e.status === "historical" ? `${1.5 * unit} ${4 * unit}` : e.status === "inferred" ? `${8 * unit} ${3 * unit} ${2 * unit} ${3 * unit}` : undefined} />
              <line className="wg-edge-hit" x1={a.x} y1={a.y} x2={b.x} y2={b.y} strokeWidth={14 * unit} onClick={() => onSelect({ edge: e.id })}>
                <title>{`${data.nodes.find((n) => n.id === e.source_id)?.name} — ${e.label} — ${sn?.name} (${STATUS_LABEL[e.status]})`}</title>
              </line>
            </g>
          );
        })}
        {data.nodes.map((n) => {
          const p = pos.get(n.id);
          if (!p) return null;
          const r = nodeR(n);
          const right = Math.cos(p.a) >= -0.01;
          const deg = (p.a * 180) / Math.PI + (right ? 0 : 180);  // along the spoke, never upside down
          const full = displayName(n.name);
          const name = full.length > 26 ? `${full.slice(0, 25)}…` : full;
          const on = sel.node === n.id;
          return (
            <g key={n.id} className={`wg-node k-${KINDS_SHOWN.includes(n.kind) ? n.kind : "other"}${on ? " on" : ""}${n.id === data.center.id ? " centre" : ""}`} transform={`translate(${p.x},${p.y})`}
              tabIndex={0} role="button" aria-pressed={on} aria-label={`${displayName(n.name)}, ${KIND_LABEL[n.kind] ?? n.kind}`}
              onClick={() => onSelect({ node: n.id })} onKeyDown={(e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); onSelect({ node: n.id }); } }}>
              <circle r={r + 8 * unit} className="wg-focus" />
              <circle r={r} strokeWidth={(on ? 3 : 1.5) * unit} />
              {n.expandable && !shown.includes(n.id) && n.id !== data.center.id && <circle r={r + 3.5 * unit} className="wg-more" strokeWidth={1 * unit} strokeDasharray={`${2 * unit} ${2 * unit}`} />}
              {n.id === data.center.id
                ? <text x={0} y={r + fs * 1.3} fontSize={fs * 1.15} textAnchor="middle" className="wg-label">{name}</text>
                : <text x={(right ? 1 : -1) * (r + 6 * unit)} y={fs * 0.35} fontSize={fs} transform={`rotate(${deg})`} textAnchor={right ? "start" : "end"} className="wg-label">{name}</text>}
            </g>
          );
        })}
      </svg>
      <p className="muted xs wg-hint">Drag to move · Ctrl/⌘ + scroll or the buttons to zoom · dashed ring = more connections available</p>
    </div>
  );
}

