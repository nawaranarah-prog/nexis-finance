/* World Graph: who owns, controls, lists or classifies a company, as reported by sources — every line has evidence
   behind it, and how sure we are is shown on the line itself. Nothing here is generated by AI. Members only (the API
   refuses visitors); visitors see what it is and how to join. */

export interface Entity { id: number; kind: string; name: string; description: string | null; wikidata_qid: string | null; wikidata_url: string | null; symbol: string | null; country: string | null; relations_fetched_at: string | null }
interface GNode extends Entity { level: number; degree: number; expandable: boolean; expanded: boolean }
interface Evidence { id: number; source_kind: string; title: string; url: string | null; publisher: string | null; published_at: string | null; retrieved_at: string; excerpt: string | null }
interface Edge { id: number; source_id: number; target_id: number; type: string; label: string; status: Status; valid_from: string | null; valid_to: string | null; note: string | null; last_verified: string; evidence: Evidence[] }
interface Graph { center: Entity; nodes: GNode[]; edges: Edge[]; counts: Record<Status, number>; truncated: number; max_nodes: number; signature: [number, string][]; fetch: { fetched: boolean; stale?: boolean; error?: string | null; fetched_at?: string } | null; since_saved?: { changed: boolean; added: number; removed: number; status_changed: number } }
interface Choice { qid: string; name: string; description: string | null; entity_id: number | null; symbol?: string | null }
interface Resolved { status: "resolved" | "ambiguous" | "not_found"; entity: Entity | null; choices: Choice[]; stale?: boolean }
interface Saved { id: number; kind: string; title: string; entity: Entity | null; notes: string | null; updated_at: string; state?: SavedState }
interface SavedState { depth: number; status: Status[]; types: string[]; expanded: number[]; signature: [number, string][] }
type Status = "verified" | "uncertain" | "historical" | "inferred";

const STATUS: { key: Status; label: string; help: string }[] = [
  { key: "verified", label: "Referenced", help: "The source statement cites a reference you can open." },
  { key: "uncertain", label: "Unreferenced", help: "Reported on Wikidata, but no reference is cited. Often true — but check before relying on it." },
  { key: "historical", label: "Ended", help: "The source gives an end date in the past." },
  { key: "inferred", label: "Computed", help: "Calculated by Nexis from market data — not a reported fact." },
];
const TYPES: { key: string; label: string }[] = [
  { key: "subsidiary_of", label: "Parent / subsidiary" },
  { key: "owned_by", label: "Ownership" },
  { key: "listed_on", label: "Listing" },
  { key: "in_industry", label: "Industry" },
  { key: "located_in", label: "Country" },
];
const KIND_LABEL: Record<string, string> = { company: "Company", organization: "Organisation", exchange: "Stock exchange", industry: "Industry", country: "Country", other: "Other (asset, brand…)", asset: "Asset", commodity: "Commodity", sector: "Sector", indicator: "Indicator", place: "Place" };
const KINDS_SHOWN = ["company", "organization", "exchange", "industry", "country", "other"];
const STATUS_LABEL = Object.fromEntries(STATUS.map((s) => [s.key, s.label])) as Record<Status, string>;

const day = (iso: string | null | undefined) => (iso ? iso.slice(0, 10) : "");
/** Wikidata items without an English label come back as their bare id; say so instead of showing "Q942632". */
const displayName = (name: string | undefined) => (name && /^Q\d+$/.test(name) ? `No English name (${name})` : name ?? "?");
const csv = (v: string | null) => (v ? v.split(",").filter(Boolean) : []);

