// ---------------------------------------------------------------------------------------------- search

export function EntitySearch({ label, onPick, focusOnMount, initial = "" }: { label: string; onPick: (e: Entity) => void; focusOnMount?: boolean; initial?: string }) {
  const [q, setQ] = useState(initial);
  const [asked, setAsked] = useState(initial.trim());
  const fid = useId();
  const input = useRef<HTMLInputElement>(null);
  const res = useMutation({
    mutationFn: (text: string) => api.get<Resolved>("/world-graph/resolve", { q: text }),
    onSuccess: (r) => { if (r.status === "resolved" && r.entity) onPick(r.entity); },
  });
  const pick = useMutation({
    mutationFn: (c: Choice) => api.post<Entity>("/world-graph/entities", { qid: c.qid }),
    onSuccess: (e) => onPick(e),
  });
  const run = (text: string) => { setAsked(text); res.mutate(text); };
  const started = useRef(false);
  useEffect(() => {
    if (started.current) return;
    started.current = true;
    if (focusOnMount) input.current?.focus();
    if (initial.trim().length >= 2) res.mutate(initial.trim());  // arrived with ?q=
  }, [focusOnMount, initial, res]);
  return (
    <div className="wg-search">
      <form className="wg-search-row" role="search" onSubmit={(e) => { e.preventDefault(); run(q.trim()); }}>
        <label className="sr-only" htmlFor={fid}>{label}</label>
        <input id={fid} ref={input} className="input" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Company or ticker, e.g. Emaar" maxLength={120} />
        <button className="btn primary" disabled={q.trim().length < 2 || res.isPending}>{res.isPending ? "Searching…" : "Search"}</button>
      </form>
      {res.error && <ErrorState error={res.error} />}
      {res.data?.status === "not_found" && <p className="np-note" role="status">Nothing found for “{asked}”. Try the company's full name.</p>}
      {res.data?.status === "ambiguous" && (
        <div className="wg-choices" role="group" aria-label="Which one did you mean?">
          <p className="small"><b>Which one did you mean?</b> We never guess — pick the right one.</p>
          {res.data.choices.map((c) => (
            <button key={c.qid} type="button" className="wg-choice" disabled={pick.isPending}
              onClick={() => (c.entity_id ? onPick({ id: c.entity_id } as Entity) : pick.mutate(c))}>
              <b>{c.name}</b>
              <span className="muted small">{c.description || "No description"} · {c.qid}{c.entity_id ? " · in Nexis" : ""}</span>
            </button>
          ))}
          {res.data.stale && <p className="muted xs">Wikidata couldn't be reached; these are the last saved results.</p>}
        </div>
      )}
      {pick.error && <div className="banner error small" role="alert">{errorMessage(pick.error)}</div>}
    </div>
  );
}

