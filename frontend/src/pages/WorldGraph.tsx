function savedHref(item: Saved): string {
  const st = item.state;
  const p = new URLSearchParams({ saved: String(item.id) });
  if (st?.depth === 2) p.set("depth", "2");
  if (st?.status?.length) p.set("status", st.status.join(","));
  if (st?.types?.length) p.set("types", st.types.join(","));
  if (st?.expanded?.length) p.set("expanded", st.expanded.join(","));
  return `/world-graph/${item.entity?.id}?${p}`;
}

function SavedLink({ item }: { item: Saved }) {
  const full = useQuery({ queryKey: ["saved-research", item.id], queryFn: () => api.get<Saved>(`/saved-research/${item.id}`), staleTime: 60_000 });
  if (!item.entity) return <span>{item.title} <span className="muted small">(company no longer available)</span></span>;
  return (
    <Link className="touch-link" to={full.data ? savedHref(full.data) : `/world-graph/${item.entity.id}?saved=${item.id}`}>
      <b>{item.title}</b> <span className="muted small">· {item.entity.name} · saved {day(item.updated_at)}</span>
    </Link>
  );
}

